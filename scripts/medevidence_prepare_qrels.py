#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build a human annotation pool from MedEvidence enriched retrieval results.

Standard library only, offline, no GPU, no database/index writes.

Examples:
  python scripts/medevidence_prepare_qrels.py \
    --results outputs/retrieval_smoke/v3_2_trial_clean/<run>/results_enriched.json \
    --depth 10 --out-dir outputs/qrels_annotation_v1

Creates:
  review_pool.csv     One row per unique (question, chunk_id) among top N of
                      BM25, Dense, and RRF, with grades left BLANK.
  question_review.csv One row per question, for corpus answerability audit.
  manifest.json       Inputs and candidate counts.

IMPORTANT:
  No relevance is inferred from token overlap or model score.
  Candidate pooling does not find every relevant chunk in the corpus.
  Unjudged chunks must NOT be treated as negative in subsequent metrics.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

METHODS = ("bm25", "dense", "hybrid")
POOL_COLUMNS = (
    "query_id", "question", "chunk_id", "doc_id", "content_kind",
    "bm25_rank", "dense_rank", "hybrid_rank", "text_excerpt",
    "relevance_grade_0_3", "mismatch_reason", "supporting_quote", "annotator_notes",
)
QUESTION_COLUMNS = (
    "query_id", "question", "corpus_answerability_yes_no_unknown",
    "verified_reference_ids", "question_notes",
)

def kind(chunk_id: str) -> str:
    for v in ("table", "figure", "abstract", "body"):
        if f":{v}:" in chunk_id:
            return v
    return "other"

def write_csv(path: Path, fields: tuple[str, ...], rows: list[dict[str, str]]) -> None:
    # BOM makes CSV open more cleanly in Microsoft Excel on Windows.
    with path.open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)

def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", required=True, type=Path, help="results_enriched.json generated by hydrate_retrieval_results.py")
    p.add_argument("--out-dir", required=True, type=Path)
    p.add_argument("--depth", type=int, default=10, help="per-method candidate pooling depth (default 10)")
    p.add_argument("--excerpt-chars", type=int, default=850)
    p.add_argument("--force", action="store_true", help="overwrite output files; WARNING: destroys existing human annotations")
    args = p.parse_args()
    if args.depth < 1 or args.excerpt_chars < 1:
        p.error("--depth and --excerpt-chars must be positive")
    if not args.results.is_file():
        p.error(f"file not found: {args.results}")
    try:
        source_bytes = args.results.read_bytes()
        payload = json.loads(source_bytes)
    except (OSError, json.JSONDecodeError) as exc:
        p.error(f"invalid JSON input: {exc}")
    questions = payload.get("questions")
    if not isinstance(questions, list) or not questions:
        p.error("JSON must have nonempty questions list")

    pool_rows: list[dict[str, str]] = []
    question_rows: list[dict[str, str]] = []
    per_question: list[dict[str, object]] = []
    seen_qids: set[str] = set()
    for q in questions:
        qid = str(q.get("id", "")).strip()
        query = str(q.get("question", "")).strip()
        if not qid or not query or qid in seen_qids:
            p.error(f"invalid or duplicated question id: {qid!r}")
        seen_qids.add(qid)
        selected: dict[str, dict[str, object]] = {}
        full_ranks: dict[str, dict[str, int]] = {}
        for method in METHODS:
            hits = q.get(method, [])
            if not isinstance(hits, list):
                p.error(f"{qid}.{method} must be a list")
            rmap: dict[str, int] = {}
            for i, hit in enumerate(hits, 1):
                cid = str(hit.get("chunk_id", "")).strip()
                if not cid:
                    p.error(f"missing chunk_id at {qid}.{method}[{i}]")
                if cid in rmap:
                    p.error(f"duplicate chunk_id in {qid}.{method}: {cid}")
                rmap[cid] = i
                if i <= args.depth:
                    prior = selected.get(cid)
                    if prior is None:
                        selected[cid] = dict(hit)
                    elif not str(prior.get("text") or "").strip() and str(hit.get("text") or "").strip():
                        selected[cid] = dict(hit)
                    elif prior.get("doc_id") and hit.get("doc_id") and prior["doc_id"] != hit["doc_id"]:
                        p.error(f"document-id mismatch for {qid}/{cid}")
            full_ranks[method] = rmap
        if not selected:
            p.error(f"no candidates for question {qid}")

        empty: list[str] = []
        for cid in selected:
            hit = selected[cid]
            text = " ".join(str(hit.get("text") or "").split())
            if not text:
                empty.append(cid)
            ranks = [full_ranks[m].get(cid, 10**10) for m in METHODS]
            pool_rows.append({
                "query_id": qid, "question": query, "chunk_id": cid,
                "doc_id": str(hit.get("doc_id") or ""), "content_kind": kind(cid),
                "bm25_rank": str(full_ranks["bm25"].get(cid, "")),
                "dense_rank": str(full_ranks["dense"].get(cid, "")),
                "hybrid_rank": str(full_ranks["hybrid"].get(cid, "")),
                "text_excerpt": text[:args.excerpt_chars],
                "relevance_grade_0_3": "", "mismatch_reason": "",
                "supporting_quote": "", "annotator_notes": "",
                "_sort": min(ranks),
            })
        if empty:
            sample = ", ".join(empty[:3])
            p.error(f"{qid}: {len(empty)} pooled chunks have empty text (example: {sample}). Use results_enriched.json, not original results.json.")
        question_rows.append({
            "query_id": qid, "question": query,
            "corpus_answerability_yes_no_unknown": "unknown",
            "verified_reference_ids": "", "question_notes": "",
        })
        per_question.append({"id": qid, "pool_size": len(selected), "methods": {m: min(args.depth, len(q.get(m, []))) for m in METHODS}})

    pool_rows.sort(key=lambda r: (r["query_id"], r["_sort"], r["chunk_id"]))
    for r in pool_rows:
        del r["_sort"]
    outputs = [args.out_dir / name for name in ("review_pool.csv", "question_review.csv", "manifest.json")]
    if not args.force and any(out.exists() for out in outputs):
        p.error(f"Output file exists. Use a fresh --out-dir; --force would overwrite human annotations: {[str(o) for o in outputs if o.exists()]}")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_csv(outputs[0], POOL_COLUMNS, pool_rows)
    write_csv(outputs[1], QUESTION_COLUMNS, question_rows)
    manifest = {
        "schema": "MedEvidence_ReviewPool_v1",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "source": str(args.results.resolve()),
        "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
        "version": payload.get("meta", {}).get("version"),
        "pool_depth_per_method": args.depth,
        "questions": len(question_rows),
        "unique_question_chunk_pairs": len(pool_rows),
        "content_types": dict(Counter(r["content_kind"] for r in pool_rows)),
        "per_question": per_question,
        "notes": [
            "Grade 0 irrelevant, 1 topical but not sufficient, 2 partially supports, 3 directly supports with important qualifications.",
            "Grade fields are intentionally blank: these are NOT automatically judged qrels.",
            "Answerability requires corpus-level verification; unknown is not no.",
            "Candidate pooling cannot establish full-corpus Recall@K; do not treat unjudged documents as relevance=0.",
        ],
    }
    outputs[2].write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[OK] {len(question_rows)} questions; {len(pool_rows)} unique question-chunk pairs; method depth={args.depth}")
    for path in outputs:
        print(path.resolve())
    return 0

if __name__ == "__main__":
    sys.exit(main())
